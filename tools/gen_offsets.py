"""Generate mod/exl/source/program/mk11_offsets.hpp from exact demangled names listed in mod/offsets.txt
(lines: CppIdent = demangled signature)."""
import os, sys
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
syms = {}
for line in open(os.path.join(R, "work/main.syms.dm.txt"), encoding="latin1"):
    p = line.rstrip("\n").split(" ", 3)
    if len(p) == 4 and p[2] == "D": syms.setdefault(p[3], int(p[0], 16))
out = ["#pragma once", "// Generated by tools/gen_offsets.py for MK11 1.0.26 (build 4F7AB1A3EEFC7EB2). Do not edit.",
       "#include <cstddef>", "", "namespace mk11::off {"]
bad = 0
for line in open(os.path.join(R, "mod/offsets.txt")):
    line = line.strip()
    if not line or line.startswith("#"): continue
    ident, sig = (s.strip() for s in line.split("=", 1))
    if sig.startswith("0x"):
        out.append(f"    constexpr ptrdiff_t {ident} = {sig};"); continue
    if sig not in syms:
        print("MISSING:", sig, file=sys.stderr); bad += 1; continue
    out.append(f"    constexpr ptrdiff_t {ident} = {syms[sig]:#x}; // {sig}")
out.append("}")
open(os.path.join(R, "mod/exl/source/program/mk11_offsets.hpp"), "w").write("\n".join(out) + "\n")
sys.exit(bad)
